/** Scoped Ghana catalogue release through OPS-005 Release Manager. */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {spawnSync} from 'node:child_process';
import * as rm from './lib/release-manager.mjs';
const root=process.cwd(), remote='root@159.65.86.24', pub='/root/.openclaw/workspace/inventory-site/public';
const files=["engines/ghana-stock.html"];
const expected={"engines/ghana-stock.html":"c1c89ae74e69c8b318d824f994e217f0c8c62a6558f6053dccbc3c4138c5f876"};
const run=(cmd,args)=>{const r=spawnSync(cmd,args,{encoding:'utf8'});if(r.status!==0)throw Error(`${cmd}: ${r.stderr}\n${r.stdout}`);return r.stdout.trim()};
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const manifest=files.map(file=>({file,before:expected[file],after:sha(fs.readFileSync(path.join(root,file)))}));
const releaseId=rm.generateReleaseId('engines',rm.gitOutput(['rev-parse','--short','HEAD'],root));
const out=process.env.GHANA_RELEASE_OUTPUT || '/tmp/ghana-release-record';
rm.TARGET_SOURCE_FILES.engines=files;
rm.TARGET_REMOTE_PATHS.engines=files.map(f=>`${pub}/${f}`);
const pre=rm.runPreDeployValidation({root,target:'engines',remote,yes:true,releaseId});
if(pre.status!=='pass')throw Error(JSON.stringify(pre));
if(!rm.snapshotRemotePaths({remote,releaseId,paths:rm.TARGET_REMOTE_PATHS.engines}))throw Error('snapshot failed');
const stage=`/root/.openclaw/workspace/inventory-site/releases/${releaseId}/staged`;
run('ssh',[remote,`mkdir -p ${stage}/css ${stage}/js ${stage}/engines`]);
for(const file of files)run('rsync',['-a',path.join(root,file),`${remote}:${stage}/${file}`]);
const installer=`import pathlib,hashlib,os,json\npub=pathlib.Path(${JSON.stringify(pub)})\nstage=pathlib.Path(${JSON.stringify(stage)})\nmanifest=json.loads(${JSON.stringify(JSON.stringify(manifest))})\nfor x in manifest:\n p=pub/x['file']; current=hashlib.sha256(p.read_bytes()).hexdigest() if p.exists() else None\n assert current==x['before'], 'Production baseline changed: '+x['file']\n assert hashlib.sha256((stage/x['file']).read_bytes()).hexdigest()==x['after']\nfor x in manifest:\n p=pub/x['file']; p.parent.mkdir(parents=True,exist_ok=True); os.replace(stage/x['file'],p)\nprint('INSTALLED')`;
run('ssh',[remote,"python3 - <<'PY'\n"+installer+"\nPY"]);
const post=await rm.runPostDeployValidation({root,target:'engines',remote,baseUrl:'https://asia-power.com'});
const record=rm.buildReleaseRecord({releaseId,git:pre.git,target:'engines',remote,timestamp:new Date().toISOString(),changedFiles:files,pre,post,backupPath:pre.backup_path,backupMode:pre.backup_mode,localReleaseJson:path.join(out,'release.json')});
record.manifest=manifest;record.authorization='User requested removal of the enquiry column from the Ghana stock catalogue; preserve displayed prices and stock.';
record.recovery.scope='Restore only engines/ghana-stock.html from the exact-file snapshot after verifying installed hash.';
rm.writeReleaseJson({remote,release:record,localDir:out});rm.printDeploymentSummary(record);
if(post.status!=='pass')process.exitCode=1;
